    private Font5x7() {
    }

    /**
     * Looks up the glyph for one printable ASCII code point (0x20-0x7E inclusive).
     *
     * @throws IllegalArgumentException if {@code codePoint} is outside the printable ASCII range
     */
    public static Glyph glyphFor(int codePoint) {
        if (codePoint < FIRST_CODE_POINT || codePoint > LAST_CODE_POINT) {
            throw new IllegalArgumentException("not a printable ASCII code point: " + codePoint);
        }
        String rows = GLYPHS[codePoint - FIRST_CODE_POINT];
        boolean[][] pixels = new boolean[HEIGHT][WIDTH];
        for (int r = 0; r < HEIGHT; r++) {
            for (int c = 0; c < WIDTH; c++) {
                pixels[r][c] = rows.charAt(r * WIDTH + c) == '#';
            }
        }
        return new Glyph(WIDTH, HEIGHT, pixels);
    }

    /** True for any code point this font can render directly (the printable ASCII range). */
    public static boolean supports(int codePoint) {
        return codePoint >= FIRST_CODE_POINT && codePoint <= LAST_CODE_POINT;
    }
