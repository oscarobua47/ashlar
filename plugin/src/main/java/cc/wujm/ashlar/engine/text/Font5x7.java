package cc.wujm.ashlar.engine.text;

/**
 * Built-in 5x7 bitmap font for printable ASCII 0x20-0x7E (95 glyphs), the classic dot-matrix
 * style: each glyph is 5 columns x 7 rows, uppercase and lowercase distinct. Encoded as one
 * 35-character row-major string per glyph (7 rows of 5 characters, '#' = ink, '.' = blank),
 * indexed by {@code codePoint - 0x20}. Pure data, no external files, ASCII-only source.
 */
